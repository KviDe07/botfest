def yandex_maps_url(query: str) -> str:
    return "https://yandex.ru/maps/?text=" + quote(query)


def maps_link(visible: str, query_or_url: str) -> str:
    """Гиперссылка в HTML Telegram: видимый текст — адрес, href — Яндекс.Карты."""
    if query_or_url.startswith(("http://", "https://")):
        url = query_or_url
    else:
        url = yandex_maps_url(query_or_url)
    return f'<a href="{html.escape(url, quote=True)}">{html.escape(visible)}</a>'


